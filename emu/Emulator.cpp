  static std::string upcase(const std::string &s)
  {
    std::string out = s;
    for (char &c : out)
      c = (char)toupper((unsigned char)c);
    return out;
  }

  static void tokenize(const std::string &line, std::vector<std::string> &tok)
  {
    size_t i = 0;
    while (i < line.size())
    {
      while (i < line.size() && isspace((unsigned char)line[i]))
        i++;
      size_t j = i;
      while (j < line.size() && !isspace((unsigned char)line[j]))
        j++;
      if (j > i)
        tok.push_back(line.substr(i, j - i));
      i = j;
    }
  }

  // Returns everything after the first whitespace-delimited token, verbatim
  // (used for `lua CODE` and `cap PATH`, whose arguments may contain spaces).
  static std::string remainder(const std::string &line)
  {
    size_t i = 0;
    while (i < line.size() && isspace((unsigned char)line[i]))
      i++;
    while (i < line.size() && !isspace((unsigned char)line[i]))
      i++;
    while (i < line.size() && isspace((unsigned char)line[i]))
      i++;
    return line.substr(i);
  }

  // [stol:emu-cmd-toggles]
  bool Emulator::setSwitchPosition(uint32_t idA, uint32_t idB, const std::string &pos)
  {
    // switchState: 1 = up (A), 2 = center, 3 = down (B). switchUp moves
    // down->center->up, switchDown moves up->center->down (see statics above).
    std::string p = upcase(pos);
    if (p == "UP")
    {
      while (switchState(idA, idB) != 1)
        switchUp(idA, idB);
      return true;
    }
    else if (p == "CENTER" || p == "MIDDLE")
    {
      int s = switchState(idA, idB);
      if (s == 1)
        switchDown(idA, idB);
      else if (s == 3)
        switchUp(idA, idB);
      return true;
    }
    else if (p == "DOWN")
    {
      while (switchState(idA, idB) != 3)
        switchDown(idA, idB);
      return true;
    }
    return false;
  }

  // [stol:emu-cmd-buttons] [stol:emu-cmd-encoder] [stol:emu-capture-fb]
  void Emulator::handleControlLine(const std::string &line)
  {
    std::vector<std::string> tok;
    tokenize(line, tok);
    if (tok.empty())
      return; // blank line: no reply
    const std::string cmd = tok[0];

    if (cmd == "quit")
    {
      quit = true;
      ctlReply("ok");
    }
    else if (cmd == "down" || cmd == "up")
    {
      if (tok.size() < 2)
      {
        ctlReply("err %s needs a button name", cmd.c_str());
        return;
      }
      auto it = nameButtonMap.find(upcase(tok[1]));
      if (it == nameButtonMap.end())
      {
        ctlReply("err unknown button %s", tok[1].c_str());
        return;
      }
      // GPIO is inverted: a button DOWN writes false, UP writes true.
      Gpio_write(it->second, cmd == "up");
      ctlReply("ok");
    }
    else if (cmd == "press")
    {
      if (tok.size() < 2)
      {
        ctlReply("err press needs a button name");
        return;
      }
      auto it = nameButtonMap.find(upcase(tok[1]));
      if (it == nameButtonMap.end())
      {
        ctlReply("err unknown button %s", tok[1].c_str());
        return;
      }
      double ms = (tok.size() >= 3) ? atof(tok[2].c_str()) : 60.0;
      Gpio_write(it->second, false); // down
      mPressButton = it->second;
      mGate = ControlGate::Press;
      mGateStartTicks = ticks();
      mGateMs = ms;
      // reply deferred until the scheduled release fires in serviceControl().
    }
    else if (cmd == "turn")
    {
      if (tok.size() < 2)
      {
        ctlReply("err turn needs a delta");
        return;
      }
      // Raw detent units, matching the SDL arrow-key accumulator.
      encoderValue += atoi(tok[1].c_str());
      ctlReply("ok");
    }
    else if (cmd == "mode" || cmd == "storage")
    {
      if (tok.size() < 2)
      {
        ctlReply("err %s needs up|center|down", cmd.c_str());
        return;
      }
      uint32_t a = (cmd == "mode") ? TOGGLE_MODE_A : TOGGLE_STORAGE_A;
      uint32_t b = (cmd == "mode") ? TOGGLE_MODE_B : TOGGLE_STORAGE_B;
      if (setSwitchPosition(a, b, tok[1]))
        ctlReply("ok");
      else
        ctlReply("err bad position %s (want up|center|down)", tok[1].c_str());
    }
    else if (cmd == "wait")
    {
      if (tok.size() < 2)
      {
        ctlReply("err wait needs milliseconds");
        return;
      }
      mGate = ControlGate::Wait;
      mGateStartTicks = ticks();
      mGateMs = atof(tok[1].c_str());
    }
    else if (cmd == "frames")
    {
      if (tok.size() < 2)
      {
        ctlReply("err frames needs a count");
        return;
      }
      mGate = ControlGate::Frames;
      mGateFrameTarget = mFrameCount + atol(tok[1].c_str());
    }
    else if (cmd == "stable")
    {
      if (tok.size() < 2)
      {
        ctlReply("err stable needs a frame count");
        return;
      }
      mStableNeed = atoi(tok[1].c_str());
      if (mStableNeed < 1)
        mStableNeed = 1;
      mStableTimeout = (tok.size() >= 3) ? atol(tok[2].c_str()) : 300;
      mStableCount = 0;
      mStableHavePrev = false;
      mStableStartFrame = mFrameCount;
      mGate = ControlGate::Stable;
    }
    else if (cmd == "cap")
    {
      std::string path = remainder(line);
      if (path.empty())
      {
        ctlReply("err cap needs a path");
        return;
      }
      // Escape for embedding in a Lua double-quoted string literal.
      std::string esc;
      for (char c : path)
      {
        if (c == '\\' || c == '"')
          esc.push_back('\\');
        esc.push_back(c);
      }
      std::string code = "return app.UIThread.saveScreenShotTo(\"" + esc + "\")";
      controlChannel().enqueueLua(code.c_str());
      mGate = ControlGate::Lua; // reply arrives from the Lua drain
    }
    else if (cmd == "lua")
    {
      std::string code = remainder(line);
      controlChannel().enqueueLua(code.c_str());
      mGate = ControlGate::Lua; // reply arrives from the Lua drain
    }
    else
    {
      ctlReply("err unknown command %s", cmd.c_str());
    }
  }

  void Emulator::onFrameRendered(DisplayBuffer *buffer)
  {
    mFrameCount++;
    if (mGate == ControlGate::Stable)
    {
      if (mStableHavePrev &&
          memcmp(mStablePrev.main, buffer->main, sizeof(buffer->main)) == 0 &&
          memcmp(mStablePrev.sub, buffer->sub, sizeof(buffer->sub)) == 0)
      {
        mStableCount++;
      }
      else
      {
        mStableCount = 0;
      }
      memcpy(mStablePrev.main, buffer->main, sizeof(buffer->main));
      memcpy(mStablePrev.sub, buffer->sub, sizeof(buffer->sub));
      mStableHavePrev = true;
    }
  }

  // [stol:emu-cmd-stable]
  void Emulator::serviceControl()
  {
    if (!useControlChannel)
      return;

    // Forward replies pushed by the Lua thread. Each reply also closes an
    // active Lua gate, except the unsolicited 'ready' handshake line.
    std::string r;
    while (controlChannel().popReply(r))
    {
      ctlReply("%s", r.c_str());
      if (mGate == ControlGate::Lua && r != "ready")
        mGate = ControlGate::None;
    }

    switch (mGate)
    {
    case ControlGate::Wait:
      if (ticks2secsD(ticks() - mGateStartTicks) * 1000.0 >= mGateMs)
      {
        mGate = ControlGate::None;
        ctlReply("ok");
      }
      break;
    case ControlGate::Press:
      if (ticks2secsD(ticks() - mGateStartTicks) * 1000.0 >= mGateMs)
      {
        Gpio_write(mPressButton, true); // release
        mGate = ControlGate::None;
        ctlReply("ok");
      }
      break;
    case ControlGate::Frames:
      if (mFrameCount >= mGateFrameTarget)
      {
        mGate = ControlGate::None;
        ctlReply("ok");
      }
      break;
    case ControlGate::Stable:
      if (mStableCount >= mStableNeed)
      {
        mGate = ControlGate::None;
        ctlReply("ok %ld", mFrameCount);
      }
      else if ((mFrameCount - mStableStartFrame) >= mStableTimeout)
      {
        mGate = ControlGate::None;
        ctlReply("err timeout");
      }
      break;
    case ControlGate::Lua:
    case ControlGate::None:
      break;
    }

    // Dispatch the next command only when no gate is pending.
    if (mGate == ControlGate::None && !mPending.empty())
    {
      std::string line = mPending.front();
      mPending.pop();
      handleControlLine(line);
    }

    // Headless with no more input and nothing pending: exit cleanly so a
    // script that omits `quit` still terminates.
    if (headless && mGate == ControlGate::None && mPending.empty() &&
        controlChannel().atEof())
    {
      quit = true;
    }
  }

  DisplayBuffer *Emulator::getDisplayBuffer()
  {
    DisplayBuffer *buffer = 0;
    readyQ.pop(&buffer);
    return buffer;
  }

  void Emulator::putDisplayBuffer(DisplayBuffer *buffer)
  {
    renderQ.push(buffer);
    SDL_Event e;
    SDL_zero(e);
    e.type = customEventType;
    SDL_PushEvent(&e);
  }

