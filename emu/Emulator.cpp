  // Control-channel reply. Prefixed with '@' so a harness can filter our
  // replies from the firmware's stdout logging (emu/hal/log.c writes logs
  // unprefixed to stdout). Documented in planning/headless-emu-plan.md §2.
  static void ctlReply(const char *fmt, ...)
  {
    char buf[512];
    va_list a;
    va_start(a, fmt);
    vsnprintf(buf, sizeof(buf), fmt, a);
    va_end(a);
    printf("@%s\n", buf);
    fflush(stdout);
  }

